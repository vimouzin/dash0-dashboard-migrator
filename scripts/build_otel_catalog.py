"""Build fixtures/otel/catalog.yaml from the pinned OpenTelemetry metric definitions (development-time only).

The catalog answers one question for scripts/build_expected.py: does an OTel metric with this name
exist at all? Sources, all byte copies under fixtures/otel/ (see fixtures/otel/NOTICE.md):
  collector-contrib/**/metadata.yaml            receiver and scraper metrics (mdatagen format)
  semantic-conventions/model/**/*metrics.yaml   semantic-convention metric registry
  java-contrib/jmx-scraper/**/*.yaml            JMX scraper rules (Kafka broker, consumer, producer)

Deterministic: same files -> same catalog. Nothing here is called by the converter or the tests.

Usage: uv run scripts/build_otel_catalog.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OTEL = ROOT / "fixtures" / "otel"
OUT = OTEL / "catalog.yaml"

SEMCONV_INSTRUMENT = {
    "counter": ("sum", True),
    "updowncounter": ("sum", False),
    "gauge": ("gauge", None),
    "histogram": ("histogram", None),
}
JMX_TYPE = {
    "counter": ("sum", True),
    "updowncounter": ("sum", False),
    "gauge": ("gauge", None),
    "state": ("sum", False),
}


def _add(catalog: dict, name: str, kind: str, monotonic, unit, attributes, source: str, deprecated: bool = False) -> None:
    entry = catalog.setdefault(name, {"type": kind, "monotonic": monotonic, "unit": unit, "attributes": [], "sources": []})
    if entry["type"] != kind:
        entry.setdefault("conflicts", []).append(f"{source}: type {kind}")
    entry["attributes"] = sorted(set(entry["attributes"]) | set(attributes or []))
    entry["sources"] = sorted(set(entry["sources"]) | {source})
    if deprecated:
        entry["deprecated"] = True


def collector(catalog: dict) -> None:
    for path in sorted((OTEL / "collector-contrib").rglob("metadata.yaml")):
        doc = yaml.safe_load(path.read_text()) or {}
        source = str(path.relative_to(OTEL))
        for name, m in sorted((doc.get("metrics") or {}).items()):
            if "sum" in m:
                kind, monotonic = "sum", bool(m["sum"].get("monotonic"))
            elif "histogram" in m:
                kind, monotonic = "histogram", None
            else:
                kind, monotonic = "gauge", None
            _add(catalog, name, kind, monotonic, m.get("unit"), m.get("attributes"), source)


def semconv(catalog: dict) -> None:
    for path in sorted((OTEL / "semantic-conventions").rglob("*metrics.yaml")):
        doc = yaml.safe_load(path.read_text()) or {}
        source = str(path.relative_to(OTEL))
        for group in doc.get("groups") or []:
            if group.get("type") != "metric" or not group.get("metric_name"):
                continue
            kind, monotonic = SEMCONV_INSTRUMENT[group["instrument"]]
            attributes = [a.get("ref") or a.get("id") for a in group.get("attributes") or [] if a.get("ref") or a.get("id")]
            _add(catalog, group["metric_name"], kind, monotonic, group.get("unit"), attributes, source, bool(group.get("deprecated")))


def _unique_anchors(text: str) -> str:
    """Rename re-defined YAML anchors (`&metric` used once per rule) so PyYAML accepts them.

    YAML lets an anchor be redefined, and an alias refers to the latest definition; PyYAML refuses
    duplicates. Each `&name` gets a numbered name and later `*name` aliases follow the latest one.
    """
    latest: dict[str, str] = {}
    counter = 0

    def rename(match: re.Match) -> str:
        nonlocal counter
        sigil, name = match.group(1), match.group(2)
        if sigil == "&":
            counter += 1
            latest[name] = f"{name}_{counter}"
        return f"{sigil}{latest.get(name, name)}"

    return re.sub(r"(?<![\w\"'])([&*])([A-Za-z_][\w-]*)", rename, text)


def jmx(catalog: dict) -> None:
    for path in sorted((OTEL / "java-contrib").rglob("*.yaml")):
        doc = yaml.safe_load(_unique_anchors(path.read_text())) or {}
        source = str(path.relative_to(OTEL))
        for rule in doc.get("rules") or []:
            prefix = rule.get("prefix") or ""
            rule_attrs = list((rule.get("metricAttribute") or {}).keys())
            for attr_name, m in sorted((rule.get("mapping") or {}).items()):
                m = m or {}
                name = prefix + (m.get("metric") or attr_name)
                kind, monotonic = JMX_TYPE[m.get("type") or rule.get("type") or "gauge"]
                attrs = rule_attrs + list((m.get("metricAttribute") or {}).keys())
                _add(catalog, name, kind, monotonic, m.get("unit") or rule.get("unit"), attrs, source)


def build() -> dict:
    catalog: dict = {}
    collector(catalog)
    semconv(catalog)
    jmx(catalog)
    return dict(sorted(catalog.items()))


HEADER = """\
# GENERATED by scripts/build_otel_catalog.py from the pinned files under fixtures/otel/ (NOTICE.md).
# Every metric name OpenTelemetry defines in those sources: type (sum|gauge|histogram), monotonic
# (sums only), unit, attribute keys, and the defining file(s). Do not edit by hand.
"""


def main() -> int:
    catalog = build()
    OUT.write_text(HEADER + yaml.safe_dump(catalog, sort_keys=False, allow_unicode=True, width=1000))
    print(f"{OUT.relative_to(ROOT)}: {len(catalog)} metrics")
    return 0


if __name__ == "__main__":
    sys.exit(main())
