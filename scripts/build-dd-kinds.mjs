#!/usr/bin/env node
// Generates mappings/datadog/_kinds.json: Datadog metric name -> the kind its integration declares in metadata.csv
// (gauge | count | rate | distribution). Used by T4 (ctx.ddKind) only for metrics WITHOUT a curated mapping entry;
// curated entries in mappings/datadog/*.yaml always win (D-18 rate corrections live there).
//
// Usage:
//   git clone --depth 1 https://github.com/DataDog/integrations-core /tmp/integrations-core
//   node scripts/build-dd-kinds.mjs /tmp/integrations-core [mappings/datadog/_kinds.json]
//
// Deterministic: sorted keys, no timestamps beyond the source note you pass in DD_KINDS_SOURCE.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [root, out = "mappings/datadog/_kinds.json"] = process.argv.slice(2);
if (!root || !existsSync(root)) {
  console.error("usage: node scripts/build-dd-kinds.mjs <integrations-core checkout> [output.json]");
  process.exit(1);
}

/** RFC 4180 CSV: quoted fields may contain commas, quotes ("") and newlines. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((x) => x !== ""));
}

const KINDS = new Set(["gauge", "count", "rate", "distribution"]);
const kinds = {};
const conflicts = [];
let files = 0;
for (const integ of readdirSync(root).sort()) {
  const f = join(root, integ, "metadata.csv");
  if (!existsSync(f)) continue;
  const [header, ...rows] = parseCsv(readFileSync(f, "utf8"));
  const iName = header.indexOf("metric_name"), iType = header.indexOf("metric_type");
  if (iName < 0 || iType < 0) continue;
  files++;
  for (const r of rows) {
    const name = (r[iName] ?? "").trim(), type = (r[iType] ?? "").trim();
    if (!name || !KINDS.has(type)) continue;
    if (kinds[name] && kinds[name] !== type) conflicts.push(`${name}: ${kinds[name]} vs ${type} (${integ})`);
    else kinds[name] = type;
  }
}
// A metric declared with different kinds by two integrations is ambiguous: leave it out (T4 then fails closed).
for (const c of conflicts) delete kinds[c.split(":")[0]];
const sorted = Object.fromEntries(Object.keys(kinds).sort().map((k) => [k, kinds[k]]));
const doc = {
  version: 1,
  source: process.env.DD_KINDS_SOURCE ?? "DataDog/integrations-core, <integration>/metadata.csv (metric_type column)",
  note: "Generated by scripts/build-dd-kinds.mjs. Used only for metrics without a curated mapping entry. Metrics declared with conflicting kinds are omitted.",
  files,
  omittedConflicts: [...new Set(conflicts.map((c) => c.split(":")[0]))].sort(),
  kinds: sorted,
};
writeFileSync(out, JSON.stringify(doc) + "\n");
const count = (t) => Object.values(sorted).filter((x) => x === t).length;
console.log(`${files} metadata.csv files -> ${Object.keys(sorted).length} metrics (gauge ${count("gauge")}, count ${count("count")}, rate ${count("rate")}, distribution ${count("distribution")}); ${doc.omittedConflicts.length} ambiguous omitted -> ${out}`);
